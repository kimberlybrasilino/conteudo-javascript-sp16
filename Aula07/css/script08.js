// Exercício 8: Calcule a área de um círculo.

alert("Área de Círculo");

let raioCirculo = parseFloat(prompt("Informe o valor do raio do círculo em centímetros: "));

let areaCirculo = 3.14 * (raioCirculo * raioCirculo);

alert("A área total do círculo de raio " + raioCirculo + "cm é: " + areaCirculo + "cm²");