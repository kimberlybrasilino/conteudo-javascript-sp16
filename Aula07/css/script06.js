// Exercício 6: Calcule a área de um quadrado.

alert("Área de Quadrado");

let ladoQuadrado = parseFloat(prompt("Informe o valor do lado do quadrado em centímetros: "));

let areaQuadrado = ladoQuadrado * ladoQuadrado;

alert("A área total do quadrado de lado " + ladoQuadrado + "cm é: " + areaQuadrado + "cm²");